-- Skill tree UI: `implemented == false` shows a purple outline (see cmgui skill tree). Default true.
do
    for skillId, info in pairs(cfg.skills) do
        if type(info) == "table" and type(skillId) == "string" then
            info.implemented = true
        end
    end

    local unimplementedPrefixes = {
        -- Fire Service perks commented out (COMING SOON); re-add "fire_service_" when restored.
    }
    for skillId, info in pairs(cfg.skills) do
        if type(info) == "table" and type(skillId) == "string" then
            for p = 1, #unimplementedPrefixes do
                local prefix = unimplementedPrefixes[p]
                if skillId:sub(1, #prefix) == prefix then
                    info.implemented = false
                end
            end
        end
    end

    local unimplementedIds = {
        -- "trapper_house_warehouse", -- skill entry commented out
    }
    for i = 1, #unimplementedIds do
        local entry = cfg.skills[unimplementedIds[i]]
        if entry then
            entry.implemented = false
        end
    end
end

